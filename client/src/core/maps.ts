const SOURCES: MapSource[] = [DESERT, JUNGLE, UNDERGROUND];

export function parseMap(src: MapSource): GameMap {
  const meta = MAPS.find((m) => m.id === src.id);
  if (!meta) throw new Error(`unknown map id ${src.id}`);
  const h = src.rows.length;
  const w = src.rows[0].length;
  const tiles = new Uint8Array(w * h);
  const spawns: Point[] = [];
  const healthSpots: Point[] = [];
  const weaponSpots: Point[] = [];
  for (let y = 0; y < h; y++) {
    const row = src.rows[y];
    if (row.length !== w) throw new Error(`map ${meta.key}: row ${y} has width ${row.length}, expected ${w}`);
    for (let x = 0; x < w; x++) {
      const c = row[x];
      const standing = { x: x * TILE + TILE / 2, y: (y + 1) * TILE - PLAYER_HH };
      if (c === '#') tiles[y * w + x] = T_SOLID;
      else if (c === '=') tiles[y * w + x] = T_PLATFORM;
      else if (c === 'S') spawns.push(standing);
      else if (c === 'H') healthSpots.push(standing);
      else if (c === 'W') weaponSpots.push(standing);
    }
  }
  return {
    id: src.id,
    key: meta.key,
    name: meta.name,
    w,
    h,
    pxW: w * TILE,
    pxH: h * TILE,
    tiles,
    spawns,
    healthSpots,
    weaponSpots,
    theme: src.theme,
  };
}

const cache = new Map<number, GameMap>();

export function getMap(id: number): GameMap {
  let m = cache.get(id);
  if (!m) {
    const src = SOURCES.find((s) => s.id === id) ?? SOURCES[0];
    m = parseMap(src);
    cache.set(id, m);
  }
  return m;
}

export const MAP_IDS = SOURCES.map((s) => s.id);
